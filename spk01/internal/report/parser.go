package report

import (
	"bufio"
	"encoding/json"
	"io"
	"time"
)

// TestEvent represents a single event produced by `go test -json` or `test2json`.
type TestEvent struct {
	Time    time.Time `json:"Time"`
	Action  string    `json:"Action"` // run, pause, cont, pass, bench, output, wait, fail, skip
	Package string    `json:"Package"`
	Test    string    `json:"Test,omitempty"`
	Elapsed float64   `json:"Elapsed,omitempty"`
	Output  string    `json:"Output,omitempty"`
}

// Summary aggregates the outcome of an execution.
type Summary struct {
	TotalEvents    int
	TestsRun       int // Number of individual tests started (Action == "run")
	TestsPassed    int
	TestsFailed    int
	TestsSkipped   int
	PackageVerdict string // "pass", "fail", or "unknown"
}

// Parse processes an NDJSON stream generated by `go test -json` or `test2json`.
func Parse(r io.Reader) (*Summary, error) {
	scanner := bufio.NewScanner(r)
	// Allow large output buffer up to 1 MB per line
	buf := make([]byte, 0, 64*1024)
	scanner.Buffer(buf, 1024*1024)

	summary := &Summary{
		PackageVerdict: "unknown",
	}

	for scanner.Scan() {
		line := scanner.Bytes()
		summary.TotalEvents++

		var event TestEvent
		if err := json.Unmarshal(line, &event); err != nil {
			// Skip unparseable lines (e.g. system noise or container logs)
			continue
		}

		if event.Test != "" {
			switch event.Action {
			case "run":
				summary.TestsRun++
			case "pass":
				summary.TestsPassed++
			case "fail":
				summary.TestsFailed++
			case "skip":
				summary.TestsSkipped++
			}
		} else {
			// Package-level final outcome
			if event.Action == "pass" || event.Action == "fail" {
				summary.PackageVerdict = event.Action
			}
		}
	}

	if err := scanner.Err(); err != nil {
		return summary, err
	}

	return summary, nil
}
